"""Generate a runnable, self-describing testbench skeleton from a module."""
import re

CLK_RE = re.compile(r'^(clk|clock|i_clk|clk_i|sys_clk|clk_in)$', re.I)
RST_RE = re.compile(r'^(rst|reset|rst_n|reset_n|rstn|resetn|nrst|n_rst|arst|arst_n|aresetn|i_rst|rst_i)$', re.I)


def _decl(kind, port):
    rng = port['range']
    sgn = ' signed' if port.get('signed') else ''
    return '    %-4s%s %s%s;' % (kind, sgn, (rng + ' ') if rng else '', port['name'])


def generate(module):
    name = module['name']
    tb = 'tb_' + name
    ports = module['ports']
    params = module['params']
    ins = [p for p in ports if p['dir'] == 'input']
    outs = [p for p in ports if p['dir'] != 'input']
    clk = next((p for p in ins if CLK_RE.match(p['name'])), None)
    rst = next((p for p in ins if RST_RE.match(p['name'])), None)
    rst_low = bool(rst and re.search(r'(_n|n)$', rst['name'], re.I) and rst['name'].lower() not in ('rst', 'reset'))
    data_ins = [p for p in ins if p is not clk and p is not rst]

    L = []
    L.append('`timescale 1ns / 1ps')
    L.append('')
    L.append('// Testbench for module "%s" (generated by VeriNest)' % name)
    L.append('// Edit the stimulus section, then press Run (F5).')
    L.append('module %s;' % tb)
    L.append('')
    if params:
        L.append('    // ---- Parameters (same defaults as the DUT) ----')
        for p in params:
            L.append('    localparam %s = %s;' % (p['name'], p['value']))
        L.append('')
    if ins:
        L.append('    // ---- DUT inputs (driven by the testbench) ----')
        for p in ins:
            L.append(_decl('reg', p))
        L.append('')
    if outs:
        L.append('    // ---- DUT outputs (observed by the testbench) ----')
        for p in outs:
            L.append(_decl('wire', p))
        L.append('')
    # instance
    L.append('    // ---- Device Under Test ----')
    head = '    %s' % name
    if params:
        head += ' #(\n' + ',\n'.join('        .%s(%s)' % (p['name'], p['name']) for p in params) + '\n    )'
    if ports:
        w = max(len(p['name']) for p in ports)
        conns = ',\n'.join('        .%s(%s)' % (p['name'].ljust(w), p['name']) for p in ports)
        L.append(head + ' dut (\n' + conns + '\n    );')
    else:
        L.append(head + ' dut ();')
    L.append('')
    if clk:
        L.append('    // ---- Clock: 10 ns period (100 MHz) ----')
        L.append('    initial %s = 1\'b0;' % clk['name'])
        L.append('    always #5 %s = ~%s;' % (clk['name'], clk['name']))
        L.append('')
    L.append('    // ---- Waveform dump ----')
    L.append('    initial begin')
    L.append('        $dumpfile("%s.vcd");' % tb)
    L.append('        $dumpvars(0, %s);' % tb)
    L.append('    end')
    L.append('')
    L.append('    // ---- Stimulus ----')
    L.append('    integer i;')
    L.append('    initial begin')
    if data_ins:
        L.append('        // initial values')
        for p in data_ins:
            L.append('        %s = 0;' % p['name'])
    if rst:
        L.append('        %s = 1\'b%d;   // assert reset' % (rst['name'], 0 if rst_low else 1))
        if clk:
            L.append('        repeat (2) @(posedge %s);' % clk['name'])
        else:
            L.append('        #20;')
        L.append('        %s = 1\'b%d;   // release reset' % (rst['name'], 1 if rst_low else 0))
    show = data_ins + outs
    fmt = ' '.join('%s=%%0d' % p['name'] for p in show) if show else ''
    args = ', '.join(p['name'] for p in show)
    L.append('')
    L.append('        // TODO: replace these random vectors with your own test cases')
    L.append('        for (i = 0; i < 10; i = i + 1) begin')
    if clk:
        L.append('            @(negedge %s);' % clk['name'])
    for p in data_ins:
        L.append('            %s = $random;' % p['name'])
    if clk:
        L.append('            @(posedge %s); #1;' % clk['name'])
    else:
        L.append('            #10;')
    if show:
        L.append('            $display("t=%%0t  %s", $time, %s);' % (fmt, args))
    L.append('        end')
    L.append('')
    L.append('        $display("Simulation finished.");')
    L.append('        $finish;')
    L.append('    end')
    L.append('')
    L.append('endmodule')
    return tb + '.v', '\n'.join(L) + '\n'
